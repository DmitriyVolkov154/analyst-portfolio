## Аналитика интернет-магазина книг

### Запрос 1: Клиенты, заказавшие определённую книгу
- **Задача:** Вывести фамилии клиентов, которые заказывали книгу 'Идиот'.
- **Навыки:** `JOIN`, `DISTINCT`, фильтрация.

### Запрос 2: Популярность книг
- **Задача:** Посчитать, сколько раз была заказана каждая книга.
- **Навыки:** `SUM`, `GROUP BY`, `LEFT JOIN`.

### Запрос 3: Клиенты по автору
- **Задача:** Найти клиентов, которые заказывали книги Достоевского.
- **Навыки:** Многотабличные `JOIN`, `DISTINCT`, фильтрация.

### Запрос 4: Самый популярный жанр
- **Задача:** Определить жанр с максимальным количеством заказов.
- **Навыки:** `SUM`, `GROUP BY`, `ORDER BY`, `LIMIT`.

### Запрос 5: Сравнение выручки по годам
- **Задача:** Сравнить ежемесячную выручку за текущий и прошлый год.
- **Навыки:** `CTE`, оконная функция `LAG`, расчёт темпов роста.
