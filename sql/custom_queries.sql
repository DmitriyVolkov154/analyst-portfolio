## Кастомные SQL-запросы для управления данными

### Запрос 1: Очистка дублей в поставках
- **Задача:** Удалить дублирующиеся записи в таблице `supply` (оставить одну запись с максимальной ценой).
- **Навыки:** `JOIN`, `TEMPORARY TABLE`, `DELETE`.

### Запрос 2: Перенос книг из поставок с новыми авторами
- **Задача:** Добавить авторов из `supply`, которых нет в `author`, и их книги в `book`.
- **Навыки:** `INSERT ... SELECT`, `LEFT JOIN`, `DISTINCT`.

### Запрос 3: Удаление непопулярных жанров
- **Задача:** Удалить жанры с количеством книг < 3, предварительно обнулив `genre_id` в `book`.
- **Навыки:** `UPDATE`, `DELETE ... USING`, подзапросы.
